// Pure presentation helpers (no DOM) so they can be unit-tested under Node.

const DATE_FORMAT = new Intl.DateTimeFormat('en-US', {
  year: 'numeric',
  month: 'short',
  day: 'numeric',
  timeZone: 'UTC', // ISO dates are calendar dates: never shift them by the viewer's time zone
});

/** "2025-03-04" -> "Mar 4, 2025". Unparseable input is returned unchanged. */
export function formatDate(iso) {
  if (!iso) return 'Date unknown';
  const date = new Date(`${iso}T00:00:00Z`);
  return Number.isNaN(date.getTime()) ? String(iso) : DATE_FORMAT.format(date);
}

/** Cosine similarity (0..1) -> whole percent, clamped. */
export function scorePercent(score) {
  const n = Number(score);
  if (!Number.isFinite(n)) return 0;
  return Math.round(Math.max(0, Math.min(1, n)) * 100);
}

/** Words for the meter so relevance never relies on colour or a bare number alone. */
export function relevanceWord(percent) {
  if (percent >= 60) return 'High';
  if (percent >= 40) return 'Moderate';
  return 'Low';
}

export function meterColour(percent) {
  if (percent >= 60) return 'bg-emerald-600';
  if (percent >= 40) return 'bg-amber-500';
  return 'bg-slate-400';
}

const BADGES = {
  summary: { label: 'AI summary', classes: 'bg-violet-100 text-violet-900 ring-violet-300' },
  DocumentReference: { label: 'Document', classes: 'bg-sky-100 text-sky-900 ring-sky-300' },
  DiagnosticReport: {
    label: 'Diagnostic report',
    classes: 'bg-emerald-100 text-emerald-900 ring-emerald-300',
  },
  Encounter: { label: 'Encounter', classes: 'bg-amber-100 text-amber-900 ring-amber-300' },
  Observation: { label: 'Observation', classes: 'bg-teal-100 text-teal-900 ring-teal-300' },
  Patient: { label: 'Patient', classes: 'bg-slate-100 text-slate-800 ring-slate-300' },
};
const FALLBACK_BADGE = { label: 'Record', classes: 'bg-slate-100 text-slate-800 ring-slate-300' };

/** Badge for a search hit or a resource. Summary hits are labelled "AI summary". */
export function badgeFor({ kind, resource_type: resourceType } = {}) {
  if (kind === 'summary') return BADGES.summary;
  return BADGES[resourceType] ?? FALLBACK_BADGE;
}

const CONFIDENCE = {
  high: 'bg-emerald-100 text-emerald-900 ring-emerald-300',
  medium: 'bg-amber-100 text-amber-900 ring-amber-300',
  low: 'bg-red-100 text-red-900 ring-red-300',
};
export function confidenceClasses(level) {
  return CONFIDENCE[level] ?? CONFIDENCE.low;
}

/** Display order of resource groups in the drawer. */
export const RESOURCE_ORDER = [
  'DocumentReference',
  'DiagnosticReport',
  'Encounter',
  'Observation',
  'Patient',
];

export function groupResources(resources) {
  const groups = new Map();
  for (const r of resources ?? []) {
    if (!groups.has(r.resource_type)) groups.set(r.resource_type, []);
    groups.get(r.resource_type).push(r);
  }
  const rank = (type) => {
    const i = RESOURCE_ORDER.indexOf(type);
    return i === -1 ? RESOURCE_ORDER.length : i;
  };
  return [...groups.entries()].sort((a, b) => rank(a[0]) - rank(b[0]) || a[0].localeCompare(b[0]));
}

/**
 * Replace base64 attachment payloads with a short note so "show JSON" stays readable.
 * Returns a deep copy; the input is not modified.
 */
export function redactAttachments(node) {
  if (Array.isArray(node)) return node.map(redactAttachments);
  if (node && typeof node === 'object') {
    const out = {};
    for (const [key, value] of Object.entries(node)) {
      out[key] =
        key === 'data' && typeof value === 'string' && value.length > 80
          ? `<base64 content omitted, ${value.length} characters>`
          : redactAttachments(value);
    }
    return out;
  }
  return node;
}

export function plural(n, singular, pluralForm = `${singular}s`) {
  return `${n} ${n === 1 ? singular : pluralForm}`;
}

/** Description of the generator for the "AI summary" provenance line. */
export function describeGenerator(generatedBy) {
  if (!generatedBy) return 'Generator unknown';
  const when = generatedBy.generated_at ? ` on ${formatDate(generatedBy.generated_at.slice(0, 10))}` : '';
  if (generatedBy.provider === 'fake') {
    return `Offline extractive baseline (no language model was used)${when}`;
  }
  return `Generated by ${generatedBy.model}${when}`;
}
